def pick_topic(topic_id: Optional[str] = None, offset: int = 0, published=()) -> Dict[str, Any]:
    """Select from IDs still available in the current publication cycle."""
    seen = set(published)
    available = [topic for topic in TOPICS if topic["id"] not in seen] or TOPICS
    if topic_id is not None:
        for topic in available:
            if topic["id"] == topic_id:
                return topic
        if any(topic["id"] == topic_id for topic in TOPICS):
            raise ValueError(f"Already published in this cycle: {topic_id}")
        raise ValueError(f"Unknown topic_id: {topic_id}")
    # Stable across processes and bank edits, with all strands mixed from day one.
    available = sorted(available, key=lambda t: sha256(t["id"].encode()).digest())
    return available[offset % len(available)]
